#!/usr/bin/env python3
"""Generate API references, or compare temporary output with committed files."""

import argparse
import difflib
from pathlib import Path
import subprocess
import re
import tempfile


ROOT = Path(__file__).resolve().parents[2]
REFERENCES = (
    ("api/v1alpha1", "galactic", ".crd-ref-docs.yaml"),
    ("api/cloud/v1alpha1", "cloud", ".crd-ref-docs-cloud.yaml"),
    ("api/network/v1alpha1", "network-bgp", ".crd-ref-docs-network-bgp.yaml"),
    ("api/network/v1alpha1", "network-gateway", ".crd-ref-docs-network-gateway.yaml"),
)
GENERATOR = "github.com/elastic/crd-ref-docs@v0.2.0"


def format_validation_patterns(text: str) -> str:
    """Quote array regex validations that crd-ref-docs v0.2.0 leaves as Markdown."""
    def quote(match):
        pattern = match[1]
        if pattern.startswith("`"):
            return match[0]
        fence = "`" * (max((len(run) for run in re.findall(r"`+", pattern)), default=0) + 1)
        return f"items:Pattern: {fence}{pattern}{fence} <br />"

    return re.sub(r"items:Pattern: ([^\n]*?) <br />", quote, text)


def generate(root: Path, check: bool) -> bool:
    """Return whether committed references match, writing only outside check mode."""
    matched = True
    with tempfile.TemporaryDirectory(prefix="galactic-api-docs-") as temporary:
        for source, name, config in REFERENCES:
            generated = Path(temporary) / f"{name}.md"
            subprocess.run(
                ["go", "run", GENERATOR, "--renderer=markdown",
                 f"--source-path={source}", f"--output-path={generated}",
                 f"--config={config}"],
                cwd=root, check=True,
            )
            banner = (
                "<!-- Generated by hack/docs/generate_api.py; do not edit. -->\n\n"
                f"Generated from `{source}`. Edit the API comments or `{config}`, "
                "then run `task generate:api-docs`. "
                "See the [API index](README.md) for resource ownership.\n\n"
            )
            expected = banner + format_validation_patterns(generated.read_text()).rstrip() + "\n"
            target = root / "docs/api" / f"{name}.md"
            if check:
                actual = target.read_text() if target.exists() else ""
                if actual != expected:
                    matched = False
                    print(f"API reference drift: {target.relative_to(root)}")
                    diff = list(difflib.unified_diff(
                        actual.splitlines(), expected.splitlines(),
                        fromfile=str(target.relative_to(root)), tofile="regenerated",
                        lineterm="",
                    ))
                    print("\n".join(diff[:60]))
                    if len(diff) > 60:
                        print(f"... {len(diff) - 60} more diff lines")
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(expected)
    return matched


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare without changing tracked files")
    args = parser.parse_args()
    if not generate(ROOT, args.check):
        print("Run task generate:api-docs and commit the updated references.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
